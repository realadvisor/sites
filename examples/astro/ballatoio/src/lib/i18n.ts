/**
 * Languages, localized routes and the site's own UI copy. Italian is the
 * default (unprefixed URLs), English lives under /en. Kit parts (form, legal,
 * consent, search) bring their own strings: pass them `LOCALE_OF[lang]`.
 */
import { legalPath, privacyPath } from '@realadvisor/sites-kit/i18n';

export type Lang = 'it' | 'en';
export const LANGS: readonly Lang[] = ['it', 'en'];
export const LOCALE_OF: Record<Lang, string> = { it: 'it-IT', en: 'en-IT' };
/** Listing texts exist only in Italian: English pages mark them `lang="it"`. */
export const CONTENT_LANG: Lang = 'it';

export const langOfPath = (pathname: string): Lang => (pathname === '/en' || pathname.startsWith('/en/') ? 'en' : 'it');

const ROUTES = {
  home: { it: '/', en: '/en' },
  buy: { it: '/comprare', en: '/en/buy' },
  rent: { it: '/affittare', en: '/en/rent' },
  listing: { it: '/immobili', en: '/en/homes' },
  sell: { it: '/vendere', en: '/en/sell' },
  sold: { it: '/venduti', en: '/en/sold' },
  team: { it: '/team', en: '/en/team' },
  contact: { it: '/contatti', en: '/en/contact' },
  about: { it: '/chi-siamo', en: '/en/about' },
  areas: { it: '/quartieri', en: '/en/neighbourhoods' },
  journal: { it: '/journal', en: '/en/journal' },
} as const;
export type Route = keyof typeof ROUTES | 'legal' | 'privacy';

/** Path of a page in a language; `sub` is a slug under it (listing, agent, district, post). */
export function href(route: Route, lang: Lang, sub?: string): string {
  if (route === 'legal') return legalPath(LOCALE_OF[lang]);
  if (route === 'privacy') return privacyPath(LOCALE_OF[lang]);
  const base: string = ROUTES[route][lang];
  return sub ? `${base === '/' ? '' : base}/${sub}` : base;
}

/** hreflang alternates for Base: every language version of the page. */
export const alternates = (route: Route, sub?: string | Partial<Record<Lang, string>>) =>
  LANGS.map((l) => ({ lang: LOCALE_OF[l], href: href(route, l, typeof sub === 'string' ? sub : sub?.[l]) }));

export const listingHref = (l: { slug: string }, lang: Lang) => href('listing', lang, l.slug);

/** `{n}` placeholders. */
export const fill = (s: string, vars: Record<string, string | number>) => s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ''));

