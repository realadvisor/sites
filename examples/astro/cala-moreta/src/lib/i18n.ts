/**
 * Languages, localized routes and the site's own UI copy. Spanish is the
 * default (unprefixed URLs), English lives under /en. Kit parts (form, legal,
 * consent, search) bring their own strings: pass them `LOCALE_OF[lang]`.
 */
import { legalPath, privacyPath } from '@realadvisor/sites-kit/i18n';

export type Lang = 'es' | 'en';
export const LANGS: readonly Lang[] = ['es', 'en'];
export const LOCALE_OF: Record<Lang, string> = { es: 'es-ES', en: 'en-ES' };
/** Listing texts exist only in Spanish: English pages mark them `lang="es"`. */
export const CONTENT_LANG = 'es';

export const langOfPath = (pathname: string): Lang => (pathname === '/en' || pathname.startsWith('/en/') ? 'en' : 'es');

const ROUTES = {
  home: { es: '/', en: '/en' },
  buy: { es: '/comprar', en: '/en/buy' },
  rent: { es: '/alquilar', en: '/en/rent' },
  listing: { es: '/inmueble', en: '/en/property' },
  sell: { es: '/vender', en: '/en/sell' },
  team: { es: '/equipo', en: '/en/team' },
  contact: { es: '/contacto', en: '/en/contact' },
  sold: { es: '/vendidas', en: '/en/sold' },
  areas: { es: '/zonas', en: '/en/areas' },
  about: { es: '/nosotros', en: '/en/about' },
  blog: { es: '/blog', en: '/en/blog' },
} as const;
export type Route = keyof typeof ROUTES | 'legal' | 'privacy';

/** Path of a page in a language; `sub` is a slug under it (listing, agent, area, post). */
export function href(route: Route, lang: Lang, sub?: string): string {
  if (route === 'legal') return legalPath(LOCALE_OF[lang]);
  if (route === 'privacy') return privacyPath(LOCALE_OF[lang]);
  const base: string = ROUTES[route][lang];
  return sub ? `${base === '/' ? '' : base}/${sub}` : base;
}

/** hreflang alternates for Base: every language version of the page. */
export const alternates = (route: Route, sub?: string | Partial<Record<Lang, string>>) =>
  LANGS.map((l) => ({ lang: LOCALE_OF[l], href: href(route, l, typeof sub === 'string' ? sub : sub?.[l]) }));

export const listingHref = (l: { slug: string }, lang: Lang) => href('listing', lang, l.slug);

