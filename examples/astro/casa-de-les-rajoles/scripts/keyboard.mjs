// Keyboard smoke test: skip link, phone menu (Enter, Escape), floor rail by keys, plan tabs, plan dialog.
import { chromium } from 'playwright';
const BASE = process.env.BASE ?? 'http://localhost:4420';
const b = await chromium.launch();
const out = [];
const p = await b.newPage({ viewport: { width: 390, height: 844 } });
await p.goto(BASE + '/');
await p.keyboard.press('Tab');
out.push(['skip link first', await p.evaluate(() => document.activeElement?.classList.contains('skip'))]);
await p.focus('[data-menu-open]');
await p.keyboard.press('Enter');
out.push(['menu opens', await p.evaluate(() => document.querySelector('[data-menu]')?.classList.contains('is-open'))]);
out.push(['focus on close', await p.evaluate(() => document.activeElement?.hasAttribute('data-menu-close'))]);
await p.keyboard.press('Escape');
out.push(['escape closes', await p.evaluate(() => !document.querySelector('[data-menu]')?.classList.contains('is-open'))]);
const d = await b.newPage({ viewport: { width: 1440, height: 900 } });
await d.goto(BASE + '/viviendas');
await d.focus('[data-floor-link="1908:5"]');
await d.keyboard.press('Enter');
out.push(['rail Enter swaps floor', await d.evaluate(() => !document.querySelector('[data-panel="1908:5"]')?.hidden && location.search.includes('planta=5'))]);
await d.focus('[data-wing-link="nueva"]');
await d.keyboard.press('Enter');
out.push(['wing switch', await d.evaluate(() => !document.querySelector('[data-rail="nueva"]')?.hidden)]);
await d.goto(BASE + '/planos');
await d.focus('[data-tab="atico"]');
await d.keyboard.press('Enter');
out.push(['type tab', await d.evaluate(() => !document.querySelector('[data-tab-panel="atico"]')?.hidden)]);
await d.focus('[data-tab-panel="atico"] .cta[data-plan]');
await d.keyboard.press('Enter');
out.push(['plan dialog open', await d.evaluate(() => document.querySelector('[data-viewer]')?.open)]);
await d.keyboard.press('Escape');
out.push(['plan dialog Escape', await d.evaluate(() => !document.querySelector('[data-viewer]')?.open)]);
const ring = await d.evaluate(() => { const a = document.querySelector('nav.main a'); a.focus(); return getComputedStyle(a).outlineStyle; });
out.push(['visible focus ring', ring !== 'none']);
console.log(out.map(([k, v]) => `${v ? 'ok  ' : 'FAIL'} ${k}`).join('\n'));
await b.close();
