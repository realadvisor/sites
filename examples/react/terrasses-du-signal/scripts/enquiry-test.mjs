// Enquiry form in the browser (preview: never sent) and without JavaScript (303 back with ?enquiry=).
import { chromium } from 'playwright';
const base = process.argv[2] ?? 'http://127.0.0.1:4512';
const DEV = '5418826d-128c-452c-8479-605681362db5';
const ok = (c, m) => console.log(`${c ? 'PASS' : 'FAIL'} ${m}`);
const b = await chromium.launch();
const p = await b.newPage();
const errs = [];
p.on('console', (m) => m.type() === 'error' && errs.push(m.text()));
await p.goto(`${base}/contact`, { waitUntil: 'networkidle' });
await p.click('#contact button[type=submit]');
ok(await p.isVisible('#contact-name-err'), 'empty submit shows field errors');
await p.goto(`${base}/contact`, { waitUntil: 'networkidle' });
await p.fill('#contact-name', 'Test');
await p.fill('#contact-email', 'test@example.com');
await p.selectOption('#contact-lot', { index: 1 });
await p.click('#contact button[type=submit]');
await p.waitForFunction(() => !document.querySelector('#contact [data-status]').hidden, null, { timeout: 10000 });
const status = (await p.textContent('#contact [data-status]')) ?? '';
ok(/aperçu|preview/i.test(status), `preview status shown (${status.slice(0, 60)})`);
const unit = await b.newPage();
await unit.goto(`${base}/appartements/4-5-pieces-rez-de-chaussee-4198742c-6626-47bb-8512-cedd362a0dbe`, { waitUntil: 'networkidle' });
ok(await unit.evaluate(() => document.querySelector('#enquiry input[name=lotId]')?.value === '4198742c-6626-47bb-8512-cedd362a0dbe'), 'unit page form carries the unit (lotId)');
const json = (body) => fetch(`${base}/api/enquiry`, { method: 'POST', body: JSON.stringify(body), headers: { 'content-type': 'application/json', accept: 'application/json', origin: base } }).then(async (r) => [r.status, await r.json()]);
const [s1, j1] = await json({ name: 'A', email: 'a@example.com', message: 'm', developmentId: DEV });
ok(s1 === 400 && j1.fields?.lotId === 'required', `development enquiry without a unit: 400 lotId required (${s1} ${JSON.stringify(j1).slice(0, 80)})`);
const form = new URLSearchParams({ name: 'A', email: 'a@example.com', message: 'm', developmentId: DEV, lotId: '4198742c-6626-47bb-8512-cedd362a0dbe', redirect: '/contact#contact' });
const res = await fetch(`${base}/api/enquiry`, { method: 'POST', body: form, redirect: 'manual', headers: { origin: base } });
const cross = await fetch(`${base}/api/enquiry`, { method: 'POST', body: form, redirect: 'manual', headers: { origin: 'https://evil.example' } });
ok(cross.status === 403, `cross-site form post refused (${cross.status})`);
ok(res.status === 303 && res.headers.get('location') === '/contact?enquiry=preview#contact', `no-JS post: ${res.status} ${res.headers.get('location')}`);
ok(!errs.length, `no console errors${errs.length ? `: ${errs.join(' | ')}` : ''}`);
await b.close();
