const DICT: Record<Lang, Dict> = { es, en };
export const tr = (l: Lang) => DICT[l];

/** Replace {name} placeholders. */
export const fill = (s: string, vars: Record<string, string | number>) => s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ''));

/** "2 disponibles" / "1 disponible" */
export const availCount = (n: number, l: Lang) => (n === 1 ? tr(l).floorAvailOne : fill(tr(l).floorAvail, { n }));

/** "12 de noviembre de 2026" / "12 November 2026" */
export const longDate = (iso: string, l: Lang) =>
  new Intl.DateTimeFormat(l === 'es' ? 'es-ES' : 'en-GB', { day: 'numeric', month: 'long', year: 'numeric' }).format(new Date(iso));
