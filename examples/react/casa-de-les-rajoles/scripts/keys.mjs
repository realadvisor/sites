// Keyboard checks (port of the Astro version's scripts/keyboard.mjs): skip link, phone menu
// (Enter, Escape), floor rail and wing switch by keys, plan tabs, plan dialog, lightbox, focus ring.
import { chromium } from 'playwright';
const base = process.argv[2] ?? 'http://127.0.0.1:4520';
const ok = (c, m) => console.log(`${c ? 'PASS' : 'FAIL'} ${m}`);
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 390, height: 844 } });
await p.goto(base + '/');
await p.keyboard.press('Tab');
ok(await p.evaluate(() => document.activeElement?.classList.contains('skip')), 'first Tab lands on skip link');
await p.focus('[data-menu-open]');
await p.keyboard.press('Enter');
ok(await p.evaluate(() => document.querySelector('[data-menu]')?.classList.contains('is-open')), 'menu opens with Enter');
ok(await p.evaluate(() => document.activeElement?.hasAttribute('data-menu-close')), 'focus moves to close');
await p.keyboard.press('Escape');
ok(await p.evaluate(() => !document.querySelector('[data-menu]')?.classList.contains('is-open') && document.activeElement?.hasAttribute('data-menu-open')), 'Escape closes, focus back on the button');
const d = await b.newPage({ viewport: { width: 1440, height: 900 } });
await d.goto(base + '/viviendas');
await d.focus('[data-floor-link="1908:5"]');
await d.keyboard.press('Enter');
ok(await d.evaluate(() => !document.querySelector('[data-panel="1908:5"]')?.hidden && location.search.includes('planta=5')), 'rail Enter swaps floor and URL');
await d.focus('[data-wing-link="nueva"]');
await d.keyboard.press('Enter');
ok(await d.evaluate(() => !document.querySelector('[data-rail="nueva"]')?.hidden && location.search.includes('ala=nueva')), 'wing switch');
await d.goto(base + '/en/floor-plans');
await d.focus('[data-tab="atico"]');
await d.keyboard.press('Enter');
ok(await d.evaluate(() => !document.querySelector('[data-tab-panel="atico"]')?.hidden), 'type tab');
await d.focus('[data-tab-panel="atico"] .cta[data-plan]');
await d.keyboard.press('Enter');
ok(await d.evaluate(() => document.querySelector('[data-viewer]')?.open && document.querySelector('[data-viewer-img]')?.src.endsWith('.svg')), 'plan dialog opens with the SVG');
await d.keyboard.press('Escape');
ok(await d.evaluate(() => !document.querySelector('[data-viewer]')?.open), 'plan dialog Escape');
await d.goto(base + '/galeria');
await d.focus('[data-gallery] a[data-i="0"]');
await d.keyboard.press('Enter');
ok(await d.evaluate(() => document.querySelector('[data-lightbox]')?.open), 'Enter opens lightbox');
await d.keyboard.press('ArrowRight');
ok(/\b2\b/.test((await d.textContent('[data-lb-count]')) ?? ''), `ArrowRight goes to photo 2 (${await d.textContent('[data-lb-count]')})`);
await d.keyboard.press('Escape');
ok(await d.evaluate(() => !document.querySelector('[data-lightbox]')?.open), 'Escape closes lightbox');
const ring = await d.evaluate(() => { const a = document.querySelector('nav.main a'); a.focus(); return getComputedStyle(a).outlineStyle; });
ok(ring !== 'none', `visible focus ring (${ring})`);
await b.close();
