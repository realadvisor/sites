// Enquiry form in the browser (preview: never sent; the unit select is required) and without JavaScript (303 back with ?enquiry=).
import { chromium } from 'playwright';
const base = process.argv[2] ?? 'http://127.0.0.1:4520';
const ok = (c, m) => console.log(`${c ? 'PASS' : 'FAIL'} ${m}`);
const b = await chromium.launch();
const p = await b.newPage();
const errs = [];
p.on('console', (m) => m.type() === 'error' && errs.push(m.text()));
await p.goto(`${base}/contacto`, { waitUntil: 'networkidle' });
await p.click('#contacto button[type=submit]');
await p.waitForTimeout(300);
ok(await p.evaluate(() => ['name', 'email', 'lot'].every((f) => !document.getElementById(`contacto-${f}-err`).hidden)), 'empty submit shows field errors');
await p.goto(`${base}/en/contact`, { waitUntil: 'networkidle' });
await p.fill('#contacto-name', 'Test');
await p.fill('#contacto-email', 'test@example.com');
await p.selectOption('#contacto-lot', { index: 1 });
await p.click('#contacto button[type=submit]');
await p.waitForFunction(() => !document.querySelector('#contacto [data-status]').hidden, null, { timeout: 10000 });
const status = await p.textContent('#contacto [data-status]');
ok(/preview/i.test(status ?? ''), `preview status shown (${status?.slice(0, 50)})`);
const dev = await p.getAttribute('#contacto input[name=developmentId]', 'value');
const form = new URLSearchParams({ name: 'A', email: 'a@example.com', message: 'm', developmentId: dev, redirect: '/contacto#contacto' });
const missing = await fetch(`${base}/api/enquiry`, { method: 'POST', body: form, headers: { origin: base, accept: 'application/json' } });
ok(missing.status === 400 && (await missing.json()).fields?.lotId === 'required', `development enquiry without a unit: ${missing.status} lotId required`);
const lot = await p.$eval('#contacto-lot option:nth-child(2)', (o) => o.value);
form.set('lotId', lot);
const res = await fetch(`${base}/api/enquiry`, { method: 'POST', body: form, redirect: 'manual', headers: { origin: base } });
const cross = await fetch(`${base}/api/enquiry`, { method: 'POST', body: form, redirect: 'manual', headers: { origin: 'https://evil.example' } });
ok(cross.status === 403, `cross-site form post refused (${cross.status})`);
ok(res.status === 303 && res.headers.get('location') === '/contacto?enquiry=preview#contacto', `no-JS post: ${res.status} ${res.headers.get('location')}`);
ok(!errs.length, `no console errors${errs.length ? `: ${errs.join(' | ')}` : ''}`);
await b.close();
