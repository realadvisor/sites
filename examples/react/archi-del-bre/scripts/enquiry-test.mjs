// Enquiry form in the browser (preview: never sent), on the contact page (unit required) and a unit page,
// and without JavaScript (303 back with ?enquiry=).
import { chromium } from 'playwright';
const base = process.argv[2] ?? 'http://127.0.0.1:4519';
const ok = (c, m) => console.log(`${c ? 'PASS' : 'FAIL'} ${m}`);
const b = await chromium.launch();
const p = await b.newPage();
const errs = [];
p.on('console', (m) => m.type() === 'error' && errs.push(m.text()));
await p.goto(`${base}/contatti`, { waitUntil: 'networkidle' });
await p.click('#enquiry button[type=submit]');
ok(await p.isVisible('#enquiry-name-err'), 'empty submit shows field errors');
await p.goto(`${base}/contatti`, { waitUntil: 'networkidle' });
await p.fill('#enquiry-name', 'Test');
await p.fill('#enquiry-email', 'test@example.com');
await p.fill('#enquiry-message', 'Buongiorno');
await p.selectOption('#enquiry-lot', { index: 1 });
await p.click('#enquiry button[type=submit]');
await p.waitForFunction(() => !document.querySelector('#enquiry [data-status]').hidden, null, { timeout: 10000 });
const st = (await p.textContent('#enquiry [data-status]')) ?? '';
ok(/Anteprima|anteprima/.test(st), `preview status shown (${st.slice(0, 50)})`);
const sitemap = await fetch(`${base}/sitemap.xml`).then((r) => r.text());
const unit = new URL(sitemap.match(/<loc>([^<]*\/de\/wohnungen\/[^<]+)<\/loc>/)[1]).pathname;
await p.goto(base + unit, { waitUntil: 'networkidle' });
ok((await p.inputValue('#enquiry-message')).startsWith('Guten Tag'), 'unit page form prefilled in German');
await p.fill('#enquiry-name', 'Test');
await p.fill('#enquiry-email', 'test@example.com');
await p.click('#enquiry button[type=submit]');
await p.waitForFunction(() => !document.querySelector('#enquiry [data-status]').hidden, null, { timeout: 10000 });
ok(/Vorschau/.test((await p.textContent('#enquiry [data-status]')) ?? ''), 'unit enquiry: German preview status');
const dev = '3894f0bf-4a44-49b0-b26b-d286b4bda70b';
const form = new URLSearchParams({ name: 'A', email: 'a@example.com', message: 'm', developmentId: dev, redirect: '/contatti#enquiry' });
const noUnit = await fetch(`${base}/api/enquiry`, { method: 'POST', body: form, headers: { origin: base, accept: 'application/json' } });
ok(noUnit.status === 400 && (await noUnit.json()).fields?.lotId === 'required', `development enquiry without a unit refused (${noUnit.status})`);
const res = await fetch(`${base}/api/enquiry`, { method: 'POST', body: new URLSearchParams({ name: 'A', email: 'a@example.com', message: 'm', redirect: '/contatti#enquiry' }), redirect: 'manual', headers: { origin: base } });
const cross = await fetch(`${base}/api/enquiry`, { method: 'POST', body: form, redirect: 'manual', headers: { origin: 'https://evil.example' } });
ok(cross.status === 403, `cross-site form post refused (${cross.status})`);
ok(res.status === 303 && res.headers.get('location') === '/contatti?enquiry=preview#enquiry', `no-JS post: ${res.status} ${res.headers.get('location')}`);
ok(!errs.length, `no console errors${errs.length ? `: ${errs.join(' | ')}` : ''}`);
await b.close();
