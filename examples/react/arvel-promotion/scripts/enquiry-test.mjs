// Enquiry forms in the browser (preview: never sent), the unit rule of a programme enquiry, and posts without JavaScript (303 back with ?enquiry=).
import { chromium } from 'playwright';
const base = process.argv[2] ?? 'http://127.0.0.1:4516';
const ok = (c, m) => console.log(`${c ? 'PASS' : 'FAIL'} ${m}`);
const b = await chromium.launch();
const p = await b.newPage();
const errs = [];
p.on('console', (m) => m.type() === 'error' && errs.push(m.text()));
await p.goto(`${base}/contact`, { waitUntil: 'networkidle' });
await p.click('#enquiry button[type=submit]');
ok(await p.isVisible('#enquiry-name-err'), 'empty submit shows field errors');
await p.goto(`${base}/contact`, { waitUntil: 'networkidle' });
await p.fill('#enquiry-name', 'Test');
await p.fill('#enquiry-email', 'test@example.com');
await p.fill('#enquiry-message', 'Bonjour');
await p.click('#enquiry button[type=submit]');
await p.waitForFunction(() => !document.querySelector('#enquiry [data-status]').hidden, null, { timeout: 10000 });
const status = await p.textContent('#enquiry [data-status]');
ok(/aperçu|non envoy/i.test(status ?? ''), `contact: preview status shown (${status?.slice(0, 60)})`);
// Programme enquiry: lot preselected from ?lot=, message prefilled.
const lot = 'c58a5357-ead2-41f5-8cb9-84367b463243';
await p.goto(`${base}/programmes/les-balcons-du-semnoz?lot=${lot}#contact`, { waitUntil: 'networkidle' });
ok((await p.inputValue('#contact-form-lot')) === lot, 'programme: ?lot= preselects the unit');
ok((await p.inputValue('#contact-form-message')).includes('T2 · 1er étage'), 'programme: message names the unit');
await p.fill('#contact-form-name', 'Test');
await p.fill('#contact-form-email', 'test@example.com');
await p.click('#contact-form button[type=submit]');
await p.waitForFunction(() => !document.querySelector('#contact-form [data-status]').hidden, null, { timeout: 10000 });
ok(/aperçu|non envoy/i.test((await p.textContent('#contact-form [data-status]')) ?? ''), 'programme: preview status shown');
const dev = await p.evaluate(() => document.querySelector('#contact-form input[name=developmentId]').value);
const post = (body, origin = base, accept) => fetch(`${base}/api/enquiry`, { method: 'POST', body: new URLSearchParams(body), redirect: 'manual', headers: { origin, ...(accept ? { accept } : {}) } });
const noLot = await post({ name: 'A', email: 'a@example.com', message: 'm', developmentId: dev }, base, 'application/json');
const noLotJson = await noLot.json();
ok(noLot.status === 400 && noLotJson.fields?.lotId === 'required', `development enquiry without a unit: ${noLot.status} lotId=${noLotJson.fields?.lotId}`);
const form = { name: 'A', email: 'a@example.com', message: 'm', redirect: '/contact#enquiry' };
const res = await post(form);
const cross = await post(form, 'https://evil.example');
ok(cross.status === 403, `cross-site form post refused (${cross.status})`);
ok(res.status === 303 && res.headers.get('location') === '/contact?enquiry=preview#enquiry', `no-JS post: ${res.status} ${res.headers.get('location')}`);
ok(!errs.length, `no console errors${errs.length ? `: ${errs.join(' | ')}` : ''}`);
await b.close();
