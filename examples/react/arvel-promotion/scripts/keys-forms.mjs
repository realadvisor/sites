// Keyboard: live unit filters on Logements (arrow keys on the type radios, checkbox with Space) and the contact form (Tab order, focus ring, validation).
import { chromium } from 'playwright';
const base = process.argv[2] ?? 'http://127.0.0.1:4516';
const ok = (c, m) => console.log(`${c ? 'PASS' : 'FAIL'} ${m}`);
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
await p.goto(base + '/programmes/les-balcons-du-semnoz/logements');
ok(await p.evaluate(() => getComputedStyle(document.querySelector('[data-unit-filters] button[type=submit]')).display === 'none'), 'live filters: the Filtrer button is hidden');
await p.focus('[data-unit-filters] input[name=type][value=""]');
await p.keyboard.press('ArrowRight');
const t = await p.evaluate(() => document.querySelector('[data-unit-filters] input[name=type]:checked').value);
const count = Number(await p.textContent('[data-unit-count]'));
const rows = await p.evaluate((t) => [...document.querySelectorAll('tr[data-unit]')].filter((r) => !r.hidden).every((r) => r.dataset.type === t), t);
ok(t === 'T1' && count > 0 && rows, `ArrowRight picks ${t}: ${count} units, table filtered`);
ok(new URL(p.url()).searchParams.get('type') === t, `URL keeps the filter (${new URL(p.url()).search})`);
await p.focus('[data-unit-filters] input[name=dispo]');
await p.keyboard.press('Space');
await p.waitForTimeout(200);
ok(await p.evaluate(() => new URLSearchParams(location.search).get('dispo') === '1' && [...document.querySelectorAll('[data-stack] [data-unit]:not([data-dim])')].every((e) => e.dataset.st === 'available')) && new URL(p.url()).searchParams.get('dispo') === '1', 'Space on "Seulement les disponibles" filters and updates the URL');
const d = await b.newPage({ viewport: { width: 1440, height: 900 } });
await d.goto(base + '/contact');
await d.focus('#enquiry-name');
await d.waitForTimeout(300);
const ring = await d.evaluate(() => getComputedStyle(document.activeElement).outlineStyle + '/' + getComputedStyle(document.activeElement).boxShadow);
ok(!/^none\/none$/.test(ring), `name field shows a focus ring (${ring})`);
await d.keyboard.type('Test');
await d.keyboard.press('Tab');
ok(await d.evaluate(() => document.activeElement?.id === 'enquiry-email'), 'Tab goes name -> e-mail');
await d.keyboard.press('Tab');
ok(await d.evaluate(() => document.activeElement?.id === 'enquiry-phone'), 'Tab goes e-mail -> phone');
ok(!(await d.evaluate(() => document.querySelector('#enquiry-email').closest('form').checkValidity())), 'form is invalid without e-mail/message (nothing submitted)');
await b.close();
